"""Check RESize's wind calculations against independent computations.

Run:  python validation/validate_wind.py            (part C needs internet)
      python validation/validate_wind.py --offline

Writes docs/validation/wind.md. Exit code 1 if a check fails.

What this proves and what it does not (also written in the report):
* A: formulas recomputed by hand (written separately from the library code).
* B: yearly energy computed by the library (exact Weibull bin probabilities) against an
  independent Simpson integration of P(v) * f(v) with the probability density.
* C: NASA POWER reachable and returning plausible mean wind speeds for some sites.
Not done: comparison with measured production or with commercial tools (WAsP, WindPRO).
"""

from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

from resize_energy.core import wind
from resize_energy.core.nasa_power import NasaPowerError, fetch_wind_climate
from resize_energy.core.wind_design import TurbineSpec, WindInputs, size_wind_plant

SITES = [("Torino", 45.07, 7.69), ("Foggia", 41.46, 15.54), ("Cagliari", 39.22, 9.12),
         ("Hamburg", 53.55, 9.99)]


def simpson_aep(speed_mean_hub: float, k: float, t: TurbineSpec, rho: float) -> float:
    """AEP by Simpson integration of P(v) f(v) dv, f = Weibull density (independent method)."""
    a = speed_mean_hub / math.gamma(1 + 1 / k)
    n = 8000  # even number of intervals on 0..40 m/s
    h = 40.0 / n
    total = 0.0
    for i in range(n + 1):
        v = i * h
        pdf = (k / a) * (v / a) ** (k - 1) * math.exp(-((v / a) ** k)) if v > 0 else 0.0
        p = wind.generic_power_kw(v, t.rated_power_kw, t.cut_in_ms, t.rated_speed_ms,
                                  t.cut_out_ms, rho)
        w = 1 if i in (0, n) else (4 if i % 2 else 2)
        total += w * p * pdf
    return 8760.0 * total * h / 3.0


def part_a() -> list[tuple[str, float, float, bool]]:
    t = TurbineSpec()
    inp = WindInputs(annual_demand_kwh=10_000_000, mean_speed_ref_ms=6.5, turbine=t)
    d = size_wind_plant(inp)
    v_hub = 6.5 * (80 / 50) ** 0.14
    gamma = math.gamma(1.5)
    p0 = 101325 * (1 - 2.25577e-5 * 100) ** 5.25588
    rho = p0 / (287.05 * (12 + 273.15))
    area = math.pi * 45**2
    cp = 2e6 / (0.5 * rho * area * 12**3)
    rows = [
        ("Mean speed at hub height (m/s)", v_hub, d.mean_speed_hub_ms),
        ("Weibull scale A, k = 2 (m/s)", v_hub / gamma, d.weibull_scale_ms),
        ("Air density at 100 m, 12 C (kg/m3)", rho, d.air_density),
        ("Swept area (m2)", area, d.swept_area_m2),
        ("Cp at rated speed", cp, d.cp_rated),
        ("Net energy = gross x 0.97 x 0.90 (kWh)", d.gross_energy_per_turbine_kwh * 0.97 * 0.9,
         d.net_energy_per_turbine_kwh),
        ("Turbines = ceil(demand / net energy)",
         math.ceil(10_000_000 / (d.gross_energy_per_turbine_kwh * 0.97 * 0.9)), d.n_turbines),
        ("Land, 5D x 7D (km2)", d.n_turbines * 35 * 90**2 / 1e6, d.array_area_km2),
    ]
    return [(n, h, lib, math.isclose(h, lib, rel_tol=1e-9)) for n, h, lib in rows]


def part_b() -> list[dict]:
    t = TurbineSpec()
    rho = wind.RHO_STANDARD
    out = []
    for mean in (5.0, 6.0, 7.0, 8.0, 9.0):
        for k in (1.8, 2.0, 2.5):
            a = mean / math.gamma(1 + 1 / k)
            lib = wind.annual_energy_kwh(
                lambda v: wind.generic_power_kw(v, t.rated_power_kw, t.cut_in_ms, t.rated_speed_ms,
                                                t.cut_out_ms, rho), k, a)
            ref = simpson_aep(mean, k, t, rho)
            diff = 100 * (lib - ref) / ref
            out.append({"mean": mean, "k": k, "lib": lib, "ref": ref, "diff": diff,
                        "cf": wind.capacity_factor(lib, t.rated_power_kw), "ok": abs(diff) < 0.3})
    return out


def part_c() -> list[dict]:
    out = []
    for name, lat, lon in SITES:
        c = fetch_wind_climate(lat, lon)
        out.append({"site": name, "v50": c.mean_speed_50m_ms, "t": c.mean_temperature_c,
                    "z": c.elevation_m, "ok": 0.5 < c.mean_speed_50m_ms < 15})
    return out


def report(path: Path, a, b, c, c_reason) -> None:
    L = ["# Wind module validation", "",
         "Generated by `validation/validate_wind.py`. Re-run it to refresh the numbers.", "",
         "## A. Formulas recomputed by hand", "",
         "Default turbine (2 MW, D = 90 m, hub 80 m, 3 / 12 / 25 m/s), 6.5 m/s at 50 m, "
         "k = 2, alpha = 0.14, 100 m, 12 C, availability 97 %, other losses 10 %, "
         "demand 10 GWh/year.", "",
         "| Quantity | Hand calculation | RESize | Match |", "|---|---|---|---|"]
    for n, h, lib, ok in a:
        L.append(f"| {n} | {h:.6g} | {lib:.6g} | {'yes' if ok else '**NO**'} |")
    L += ["", "## B. Yearly energy: exact bins vs independent Simpson integration", "",
          "Generic power curve of the default turbine at standard density; tolerance 0.3 %.", "",
          "| Mean speed m/s | k | RESize MWh | Simpson MWh | Diff % | Capacity factor | Ok |",
          "|---|---|---|---|---|---|---|"]
    for r in b:
        L.append(f"| {r['mean']:.1f} | {r['k']:.1f} | {r['lib'] / 1e3:.1f} | {r['ref'] / 1e3:.1f} | "
                 f"{r['diff']:+.3f} | {r['cf']:.1%} | {'yes' if r['ok'] else '**NO**'} |")
    L += ["", "## C. NASA POWER (live data)", ""]
    if c_reason:
        L += [f"Not run: {c_reason}", ""]
    else:
        L += ["| Site | Mean speed at 50 m (m/s) | Mean temperature (C) | Elevation (m) | Plausible |",
              "|---|---|---|---|---|"]
        for r in c:
            t = "-" if r["t"] is None else f"{r['t']:.1f}"
            z = "-" if r["z"] is None else f"{r['z']:.0f}"
            L.append(f"| {r['site']} | {r['v50']:.2f} | {t} | {z} | {'yes' if r['ok'] else '**NO**'} |")
        L.append("")
    L += ["## Limits of this validation", "",
          "- B compares two numerical methods of the same model: it checks the integration, not "
          "the physics of the generic power curve.",
          "- The generic power curve is smoother than a measured one (IEC 61400-12-1); real "
          "turbines need their own curve.",
          "- NASA POWER is a coarse reanalysis (about 50 km): sites in complex terrain or on "
          "the coast can be far from reality.",
          "- No comparison with measured production or with commercial software (WAsP, WindPRO).",
          "- Results are preliminary-design quality, see DISCLAIMER.md.", ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(L), encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--offline", action="store_true")
    ap.add_argument("--out", default="docs/validation/wind.md")
    args = ap.parse_args()
    a, b = part_a(), part_b()
    c, reason = [], None
    if args.offline:
        reason = "run with internet access (without --offline)."
    else:
        try:
            c = part_c()
        except NasaPowerError as exc:
            reason = f"NASA POWER not reachable ({exc})."
    report(Path(args.out), a, b, c, reason)
    print(Path(args.out).read_text(encoding="utf-8"))
    ok = all(r[3] for r in a) and all(r["ok"] for r in b) and all(r["ok"] for r in c)
    return 0 if ok and (reason is None or args.offline) else 1


if __name__ == "__main__":
    sys.exit(main())

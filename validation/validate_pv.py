"""Check RESize's PV sizing against PVGIS and against independent hand calculations.

Run:  python validation/validate_pv.py            (needs internet for the PVGIS part)
      python validation/validate_pv.py --offline  (hand-calculation checks only)

Writes docs/validation/pv.md. Exit code 1 if any check fails.

What this does and does not prove (also written in the report):
* Part A (electrical): every number is recomputed with explicit formulas written independently
  of the library code and compared.
* Part B (energy): the energy of the sized plant is compared with PVGIS' own yield for the same
  location, tilt, azimuth and losses. RESize uses PR = PVGIS' E_y / H(i), so this checks the
  chain of formulas (and unit handling), not PVGIS itself. It is not a comparison against
  measured plants.
"""

from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

from resize_energy.core.pv_design import InverterSpec, ModuleSpec, PVInputs, size_pv_system
from resize_energy.core.pvgis import PVGISError, fetch_pvcalc

SITES = [  # name, lat, lon
    ("Torino", 45.07, 7.69),
    ("Milano", 45.46, 9.19),
    ("Roma", 41.90, 12.50),
    ("Palermo", 38.12, 13.36),
    ("Berlin", 52.52, 13.40),
    ("Madrid", 40.42, -3.70),
]
TILT, AZIMUTH, LOSS = 30.0, 0.0, 14.0
DEMAND_KWH = 4500.0
TOL_ENERGY_PCT = 3.0  # allowed difference caused by rounding to whole modules


def electrical_checks() -> list[tuple[str, float, float, bool]]:
    """Recompute string limits by hand for the default module/inverter."""
    m, inv = ModuleSpec(), InverterSpec()
    inp = PVInputs(annual_demand_kwh=DEMAND_KWH, annual_irradiation_kwh_m2=1700.0,
                   performance_ratio=0.80, t_min_c=-10.0, t_cell_max_c=70.0, module=m, inverter=inv)
    d = size_pv_system(inp)
    voc_cold = m.voc_v * (1 + m.temp_coeff_voc_pct_per_c / 100 * (-10 - 25))
    vmp_hot = m.vmp_v * (1 + m.temp_coeff_vmp_pct_per_c / 100 * (70 - 25))
    vmp_cold = m.vmp_v * (1 + m.temp_coeff_vmp_pct_per_c / 100 * (-10 - 25))
    n_max_voc = math.floor(inv.vdc_max_v / voc_cold)      # inverter absolute voltage limit
    n_max_mppt = math.floor(inv.mppt_vmax_v / vmp_cold)   # MPPT window upper edge, cold
    n_max = min(n_max_voc, n_max_mppt)
    n_min = math.ceil(inv.mppt_vmin_v / vmp_hot)
    cap = math.floor(inv.imax_per_mppt_a / m.isc_a) * inv.n_mppt
    target = DEMAND_KWH / (1700.0 * 0.80)
    rows = [
        ("Voc at -10 C (V)", voc_cold, d.voc_cold_string_v / d.n_series),
        ("Vmp at 70 C (V)", vmp_hot, d.vmp_hot_string_v / d.n_series),
        ("Vmp at -10 C (V)", vmp_cold, d.vmp_cold_string_v / d.n_series),
        ("Max modules by Vdc,max (Voc cold)", n_max_voc, math.floor(inv.vdc_max_v / (d.voc_cold_string_v / d.n_series))),
        ("Max modules per string (min of Voc and MPPT-cold limits)", n_max, d.n_series_max),
        ("Min modules per string", n_min, d.n_series_min),
        ("Strings the inverter accepts", cap, d.string_capacity),
        ("Target peak power (kWp)", target, d.target_kwp),
    ]
    return [(n, hand, lib, math.isclose(hand, lib, rel_tol=1e-6)) for n, hand, lib in rows]


def energy_checks() -> list[dict]:
    out = []
    for name, lat, lon in SITES:
        r = fetch_pvcalc(lat, lon, TILT, AZIMUTH, LOSS)
        h, y, pr = r.annual_irradiation_kwh_m2, r.annual_yield_kwh_per_kwp, r.implied_performance_ratio
        inp = PVInputs(annual_demand_kwh=DEMAND_KWH, annual_irradiation_kwh_m2=h, performance_ratio=pr)
        d = size_pv_system(inp)
        reference = d.dc_power_kwp * y  # PVGIS yield scaled to the installed power
        diff = 100 * (d.annual_energy_kwh - reference) / reference
        out.append({"site": name, "H": h, "Ey": y, "PR": pr, "kwp": d.dc_power_kwp,
                    "resize": d.annual_energy_kwh, "pvgis": reference, "diff": diff,
                    "ok": abs(diff) <= TOL_ENERGY_PCT})
    return out


def write_report(path: Path, elec, energy, offline_reason: str | None) -> None:
    L = ["# PV module validation", "",
         "Generated by `validation/validate_pv.py`. Re-run it to refresh the numbers.", "",
         "## A. Electrical design (independent hand calculation)", "",
         "Default module (410 Wp, Voc 37.5 V, Vmp 31.5 V, Isc 13.9 A, beta_Voc -0.27 %/C, "
         "beta_Vmp -0.34 %/C) and default inverter (1000 V, MPPT 200-800 V, 26 A x 2).", "",
         "| Quantity | Hand calculation | RESize | Match |", "|---|---|---|---|"]
    for n, hand, lib, ok in elec:
        L.append(f"| {n} | {hand:.4g} | {lib:.4g} | {'yes' if ok else '**NO**'} |")
    L += ["", "## B. Yearly energy vs PVGIS", ""]
    if offline_reason:
        L += [f"Not run: {offline_reason}", ""]
    else:
        L += [f"Fixed mounting, tilt {TILT:.0f} deg, south, system losses {LOSS:.0f} %, "
              f"demand {DEMAND_KWH:.0f} kWh/year, PR taken from PVGIS (E_y / H(i)). "
              f"Tolerance {TOL_ENERGY_PCT:.0f} % (whole-module rounding).", "",
              "| Site | H(i) kWh/m2 | PVGIS E_y kWh/kWp | PR | Installed kWp | RESize kWh | "
              "PVGIS kWh | Diff % | Ok |", "|---|---|---|---|---|---|---|---|---|"]
        for e in energy:
            L.append(f"| {e['site']} | {e['H']:.0f} | {e['Ey']:.0f} | {e['PR']:.3f} | {e['kwp']:.2f} | "
                     f"{e['resize']:.0f} | {e['pvgis']:.0f} | {e['diff']:+.2f} | "
                     f"{'yes' if e['ok'] else '**NO**'} |")
        L.append("")
    L += ["## Limits of this validation", "",
          "- Part B uses PR from PVGIS itself, so it verifies RESize's formulas and unit handling, "
          "not PVGIS and not real plants.",
          "- No comparison with measured production or with NREL SAM yet (planned).",
          "- Temperature extremes (-10 C / 70 C) are inputs, not site-derived.",
          "- Results are preliminary-design quality, see DISCLAIMER.md.", ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(L), encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--offline", action="store_true")
    ap.add_argument("--out", default="docs/validation/pv.md")
    args = ap.parse_args()
    elec = electrical_checks()
    energy, reason = [], None
    if args.offline:
        reason = "run with internet access (without --offline)."
    else:
        try:
            energy = energy_checks()
        except PVGISError as exc:
            reason = f"PVGIS not reachable ({exc})."
    write_report(Path(args.out), elec, energy, reason)
    ok = all(c[3] for c in elec) and all(e["ok"] for e in energy)
    for line in Path(args.out).read_text(encoding="utf-8").splitlines():
        print(line)
    return 0 if ok and (reason is None or args.offline) else 1


if __name__ == "__main__":
    sys.exit(main())
